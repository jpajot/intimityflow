export function colorToHex(color) {
  if (color.hex) return color.hex;
  if (color.rgb_r !== undefined) {
    const r = Math.round(color.rgb_r).toString(16).padStart(2, "0");
    const g = Math.round(color.rgb_g).toString(16).padStart(2, "0");
    const b = Math.round(color.rgb_b).toString(16).padStart(2, "0");
    return `#${r}${g}${b}`;
  }
  return "#cccccc";
}

export function tcxDisplayName(color) {
  return `${color.code} - ${color.name}`;
}