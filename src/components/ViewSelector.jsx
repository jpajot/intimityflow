import { useState, useEffect, useCallback, useMemo } from "react";
import { base44 } from "@/api/base44Client";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Dialog, DialogContent, DialogHeader, DialogTitle, DialogFooter } from "@/components/ui/dialog";
import { Checkbox } from "@/components/ui/checkbox";
import { Label } from "@/components/ui/label";
import { Plus, Pencil, Trash2, Loader2, LayoutList, X, ShieldCheck, Pin, GripVertical } from "lucide-react";
import { DragDropContext, Droppable, Draggable } from "@hello-pangea/dnd";
import { Tabs, TabsList, TabsTrigger, TabsContent } from "@/components/ui/tabs";
import { Badge } from "@/components/ui/badge";

const STORAGE_KEY = (pageKey) => `list_active_view_${pageKey}`;
const DEFAULT_FILTERS = { operator: "and", filters: [] };

function emptyFilter() {
  return { operator: "and", field: "", values: [] };
}

function applyFilters(rows, filtersConfig) {
  if (!filtersConfig || !filtersConfig.filters || filtersConfig.filters.length === 0) return rows;
  const active = filtersConfig.filters.filter((f) => f.field && f.values.length > 0);
  if (active.length === 0) return rows;
  return rows.filter((row) => {
    let result = matchFilter(active[0], row);
    for (let i = 1; i < active.length; i++) {
      const op = active[i].operator || "and";
      const match = matchFilter(active[i], row);
      if (op === "or") result = result || match;
      else if (op === "not") result = result && !match;
      else result = result && match; // and
    }
    return result;
  });
}

function matchFilter(f, row) {
  const val = f.getValue ? f.getValue(row) : row[f.field];
  return f.values.includes(val);
}

function formatFieldLabel(key) {
  return key.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

function schemaToColumns(schema) {
  const props = schema?.properties || {};
  return Object.entries(props).map(([key, def]) => ({
    id: key,
    label: formatFieldLabel(key),
    _autoGenerated: true,
    sortKey: (row) => row[key] || "",
    render: (row) => {
      const val = row[key];
      if (val == null || val === "") return "—";
      if (Array.isArray(val)) return val.join(", ") || "—";
      return String(val);
    },
  }));
}

export default function ViewSelector({ pageKey, allColumns, onColumnsChange, filterableFields = [], rows = [], onFilteredRowsChange, entityNames = [], fixedColumnIds = [], onFixedColumnIdsChange = null }) {
  const [views, setViews] = useState([]);
  const [schemaColumns, setSchemaColumns] = useState([]);
  const [activeViewId, setActiveViewId] = useState(() => localStorage.getItem(STORAGE_KEY(pageKey)) || "default");
  const [activeFiltersConfig, setActiveFiltersConfig] = useState(DEFAULT_FILTERS);
  const [showManage, setShowManage] = useState(false);
  const [mode, setMode] = useState("list");
  const [editingView, setEditingView] = useState(null);
  const [formName, setFormName] = useState("");
  const [formColumnIds, setFormColumnIds] = useState([]);
  const [formFilters, setFormFilters] = useState(DEFAULT_FILTERS);
  const [formRoles, setFormRoles] = useState([]);
  const [roleInput, setRoleInput] = useState("");
  const [saving, setSaving] = useState(false);
  const [loading, setLoading] = useState(true);
  const [dialogTab, setDialogTab] = useState("columns");
  const [formFixedColumnIds, setFormFixedColumnIds] = useState([]);
  const [columnSearch, setColumnSearch] = useState("");

  useEffect(() => {
    if (entityNames.length === 0) return;
    Promise.all(
      entityNames.map((name) =>
        base44.entities[name]?.list("-created_date", 50).catch(() => [])
      )
    ).then((results) => {
      const existingIds = new Set(allColumns.map((c) => c.id));
      const SKIP = new Set(["id", "created_date", "updated_date", "created_by"]);
      const extra = [];
      const seen = new Set(existingIds);
      // Collect all keys across all records to handle sparse fields
      for (const records of results) {
        if (!records?.length) continue;
        const allKeys = new Set(records.flatMap((r) => Object.keys(r)));
        for (const key of allKeys) {
          if (SKIP.has(key) || seen.has(key) || key.endsWith("_id") || key.endsWith("_ids")) continue;
          seen.add(key);
          extra.push({
            id: key,
            label: formatFieldLabel(key),
            _autoGenerated: true,
            sortKey: (row) => row[key] || "",
            render: (row) => {
              const val = row[key];
              if (val == null || val === "") return "—";
              if (Array.isArray(val)) return val.join(", ") || "—";
              return String(val);
            },
          });
        }
      }
      setSchemaColumns(extra);
    });
  }, [entityNames.join(",")]);

  const mergedColumns = [...allColumns, ...schemaColumns];

  useEffect(() => {
    base44.entities.ListViewConfig.filter({ page_key: pageKey }).then((data) => {
      setViews(data);
      setLoading(false);
    });
  }, [pageKey]);

  const applyView = useCallback((viewId, viewList) => {
    const list = viewList || views;
    if (viewId === "default") {
      onColumnsChange(mergedColumns);
      const stored = tryParseJSON(localStorage.getItem(`${STORAGE_KEY(pageKey)}_filters`)) || DEFAULT_FILTERS;
      setActiveFiltersConfig(stored);
      if (onFixedColumnIdsChange) onFixedColumnIdsChange([]);
    } else {
      const view = list.find((v) => v.id === viewId);
      if (view) {
        const ordered = (view.column_ids || []).map((id) => mergedColumns.find((c) => c.id === id)).filter(Boolean);
        onColumnsChange(ordered.length > 0 ? ordered : mergedColumns);
        setActiveFiltersConfig(view.filters_config || DEFAULT_FILTERS);
        if (onFixedColumnIdsChange) onFixedColumnIdsChange(view.fixed_column_ids || []);
      }
    }
  }, [views, allColumns, onColumnsChange, pageKey, onFixedColumnIdsChange]);

  useEffect(() => {
    if (!loading) applyView(activeViewId);
  }, [loading, activeViewId, views]);

  // Apply filters to rows whenever rows or activeFiltersConfig changes
  useEffect(() => {
    if (!onFilteredRowsChange) return;
    const enrichedConfig = {
      ...activeFiltersConfig,
      filters: (activeFiltersConfig.filters || []).map((f) => {
        const field = filterableFields.find((ff) => ff.id === f.field);
        return { ...f, getValue: field?.getValue };
      }),
    };
    onFilteredRowsChange(applyFilters(rows, enrichedConfig));
  }, [rows, activeFiltersConfig, filterableFields]);

  const switchView = (viewId) => {
    setActiveViewId(viewId);
    localStorage.setItem(STORAGE_KEY(pageKey), viewId);
    applyView(viewId);
  };

  const openNew = () => {
    setFormName("");
    setFormColumnIds(mergedColumns.map((c) => c.id));
    setFormFilters(DEFAULT_FILTERS);
    setFormRoles([]);
    setFormFixedColumnIds([]);
    setRoleInput("");
    setEditingView(null);
    setDialogTab("columns");
    setMode("new");
  };

  const openEdit = (view) => {
    setFormName(view.name);
    const inView = (view.column_ids || []).filter((id) => mergedColumns.find((c) => c.id === id));
    setFormColumnIds([...inView]);
    setFormFilters(view.filters_config || DEFAULT_FILTERS);
    setFormRoles(view.allowed_roles || []);
    setFormFixedColumnIds(view.fixed_column_ids || []);
    setRoleInput("");
    setEditingView(view);
    setDialogTab("columns");
    setMode("edit");
  };

  const toggleCol = (id) => {
    setFormColumnIds((prev) => prev.includes(id) ? prev.filter((x) => x !== id) : [...prev, id]);
  };

  const moveCol = (id, dir) => {
    setFormColumnIds((prev) => {
      const idx = prev.indexOf(id);
      const next = [...prev];
      const swap = idx + dir;
      if (swap < 0 || swap >= next.length) return prev;
      [next[idx], next[swap]] = [next[swap], next[idx]];
      return next;
    });
  };

  const addFilter = () => setFormFilters((f) => ({ ...f, filters: [...f.filters, emptyFilter()] }));

  const removeFilter = (idx) => setFormFilters((f) => ({ ...f, filters: f.filters.filter((_, i) => i !== idx) }));

  const updateFilter = (idx, patch) => setFormFilters((f) => ({
    ...f,
    filters: f.filters.map((fi, i) => i === idx ? { ...fi, ...patch } : fi),
  }));

  const getFieldOptions = (fieldId) => {
    const field = filterableFields.find((f) => f.id === fieldId);
    if (!field) return [];
    return [...new Set(rows.map((r) => field.getValue(r)).filter(Boolean))].sort();
  };

  const toggleFilterValue = (idx, val) => {
    setFormFilters((f) => {
      const fi = f.filters[idx];
      const values = fi.values.includes(val) ? fi.values.filter((v) => v !== val) : [...fi.values, val];
      return { ...f, filters: f.filters.map((x, i) => i === idx ? { ...x, values } : x) };
    });
  };

  const addRole = () => {
    const r = roleInput.trim();
    if (r && !formRoles.includes(r)) setFormRoles((prev) => [...prev, r]);
    setRoleInput("");
  };

  const removeRole = (r) => setFormRoles((prev) => prev.filter((x) => x !== r));

  const handleSave = async () => {
    if (!formName.trim()) return;
    setSaving(true);
    const data = {
      page_key: pageKey,
      name: formName.trim(),
      column_ids: formColumnIds.filter((id) => mergedColumns.find((c) => c.id === id)),
      fixed_column_ids: formFixedColumnIds,
      filters_config: formFilters,
      allowed_roles: formRoles,
    };
    if (editingView) {
      await base44.entities.ListViewConfig.update(editingView.id, data);
      const updated = views.map((v) => v.id === editingView.id ? { ...v, ...data } : v);
      setViews(updated);
      if (activeViewId === editingView.id) {
        onColumnsChange(formColumnIds.map((id) => allColumns.find((c) => c.id === id)).filter(Boolean));
        setActiveFiltersConfig(formFilters);
        if (onFixedColumnIdsChange) onFixedColumnIdsChange(formFixedColumnIds);
      }
    } else {
      const created = await base44.entities.ListViewConfig.create(data);
      const updated = [...views, created];
      setViews(updated);
      switchView(created.id);
    }
    setSaving(false);
    setMode("list");
  };

  const handleDelete = async (view) => {
    await base44.entities.ListViewConfig.delete(view.id);
    const updated = views.filter((v) => v.id !== view.id);
    setViews(updated);
    if (activeViewId === view.id) switchView("default");
  };

  const activeLabel = activeViewId === "default" ? "Default" : views.find((v) => v.id === activeViewId)?.name || "Default";
  const activeFilterCount = (activeFiltersConfig.filters || []).filter((f) => f.field && f.values.length > 0).length;

  return (
    <div className="flex items-center gap-2">
      <LayoutList className="w-4 h-4 text-muted-foreground shrink-0" />
      <Select value={activeViewId} onValueChange={switchView}>
        <SelectTrigger className="h-8 text-xs w-36 border-dashed">
          <SelectValue>{activeLabel}</SelectValue>
        </SelectTrigger>
        <SelectContent>
          <SelectItem value="default">Default</SelectItem>
          {views.map((v) => <SelectItem key={v.id} value={v.id}>{v.name}</SelectItem>)}
        </SelectContent>
      </Select>
      <Button variant="outline" size="sm" className="h-8 text-xs gap-1.5" onClick={() => { setMode("list"); setShowManage(true); }}>
        <Pencil className="w-3 h-3" /> Manage Views
        {activeFilterCount > 0 && <Badge className="ml-1 px-1.5 py-0 text-[10px] h-4">{activeFilterCount}</Badge>}
      </Button>

      <Dialog open={showManage} onOpenChange={(o) => { if (!o) { setShowManage(false); setMode("list"); } }}>
        <DialogContent className="max-w-lg">
          <DialogHeader>
            <DialogTitle>
              {mode === "list" ? "Views" : mode === "new" ? "New View" : `Edit: ${editingView?.name}`}
            </DialogTitle>
          </DialogHeader>

          {mode === "list" && (
            <div className="space-y-3">
              {loading ? (
                <div className="flex justify-center py-6"><Loader2 className="w-5 h-5 animate-spin text-muted-foreground" /></div>
              ) : (
                <>
                  <div className="flex items-center gap-2 p-2.5 rounded-lg border border-border bg-muted/30">
                    <span className="flex-1 text-sm font-medium">Default</span>
                    <span className="text-xs text-muted-foreground">All columns</span>
                  </div>
                  {views.map((v) => (
                   <div key={v.id} className="flex items-center gap-2 p-2.5 rounded-lg border border-border">
                     <span className="flex-1 text-sm font-medium">{v.name}</span>
                     <span className="text-xs text-muted-foreground">{v.column_ids?.length} cols</span>
                     {v.filters_config?.filters?.filter(f => f.field && f.values?.length).length > 0 && (
                       <Badge variant="secondary" className="text-[10px] px-1.5">{v.filters_config.filters.filter(f => f.field && f.values?.length).length} filter{v.filters_config.filters.filter(f => f.field && f.values?.length).length > 1 ? "s" : ""}</Badge>
                     )}
                     {v.allowed_roles?.length > 0 && (
                       <Badge variant="outline" className="text-[10px] px-1.5 gap-0.5"><ShieldCheck className="w-2.5 h-2.5 mr-0.5" />{v.allowed_roles.join(", ")}</Badge>
                     )}
                     <Button variant="ghost" size="icon" className="h-7 w-7" onClick={() => openEdit(v)}><Pencil className="w-3.5 h-3.5" /></Button>
                     <Button variant="ghost" size="icon" className="h-7 w-7 text-destructive" onClick={() => handleDelete(v)}><Trash2 className="w-3.5 h-3.5" /></Button>
                   </div>
                  ))}
                  {views.length === 0 && <p className="text-sm text-muted-foreground text-center py-4">No custom views yet</p>}
                </>
              )}
              <Button onClick={openNew} className="gap-2 w-full" variant="outline">
                <Plus className="w-4 h-4" /> New View
              </Button>
            </div>
          )}

          {(mode === "new" || mode === "edit") && (
            <div className="space-y-4">
              <div className="space-y-1.5">
                <Label className="text-xs">View Name</Label>
                <Input value={formName} onChange={(e) => setFormName(e.target.value)} placeholder="e.g. Sales View" autoFocus />
              </div>

              <Tabs value={dialogTab} onValueChange={setDialogTab}>
                <TabsList className="w-full">
                  <TabsTrigger value="columns" className="flex-1 text-xs">Columns</TabsTrigger>
                  <TabsTrigger value="filters" className="flex-1 text-xs">
                    Filters
                    {formFilters.filters.filter(f => f.field && f.values.length > 0).length > 0 && (
                      <Badge className="ml-1.5 px-1.5 py-0 text-[10px] h-4">{formFilters.filters.filter(f => f.field && f.values.length > 0).length}</Badge>
                    )}
                  </TabsTrigger>
                  <TabsTrigger value="roles" className="flex-1 text-xs">
                    Roles
                    {formRoles.length > 0 && (
                      <Badge variant="secondary" className="ml-1.5 px-1.5 py-0 text-[10px] h-4">{formRoles.length}</Badge>
                    )}
                  </TabsTrigger>
                </TabsList>

                {/* COLUMNS TAB */}
                <TabsContent value="columns" className="mt-3">
                  <div className="mb-2">
                    <Input
                      value={columnSearch}
                      onChange={(e) => setColumnSearch(e.target.value)}
                      placeholder="Search columns…"
                      className="h-7 text-xs"
                    />
                  </div>
                  {(() => {
                    const q = columnSearch.toLowerCase();
                    const checked = formColumnIds.map((id) => mergedColumns.find((c) => c.id === id)).filter(Boolean);
                    const unchecked = mergedColumns.filter((c) => !formColumnIds.includes(c.id));
                    const filteredChecked = q ? checked.filter((c) => c.label.toLowerCase().includes(q)) : checked;
                    const filteredUnchecked = q ? unchecked.filter((c) => c.label.toLowerCase().includes(q)) : unchecked;
                    const handleDragEnd = (result) => {
                      if (!result.destination) return;
                      const newIds = [...formColumnIds];
                      const [removed] = newIds.splice(result.source.index, 1);
                      newIds.splice(result.destination.index, 0, removed);
                      setFormColumnIds(newIds);
                    };
                    return (
                      <div className="border border-border rounded-lg overflow-hidden">
                        <DragDropContext onDragEnd={handleDragEnd}>
                          <Droppable droppableId="columns-checked">
                            {(provided) => (
                              <div ref={provided.innerRef} {...provided.droppableProps} className="max-h-44 overflow-y-auto divide-y divide-border">
                                {filteredChecked.map((col, index) => {
                                  const isPinned = formFixedColumnIds.includes(col.id);
                                  return (
                                    <Draggable key={col.id} draggableId={col.id} index={index}>
                                      {(drag, snapshot) => (
                                        <div
                                          ref={drag.innerRef}
                                          {...drag.draggableProps}
                                          style={drag.draggableProps.style}
                                          className={`flex items-center gap-2.5 px-3 py-2 bg-card ${isPinned ? "bg-primary/5" : ""} ${snapshot.isDragging ? "shadow-lg border border-border" : ""}`}
                                        >
                                          <div {...drag.dragHandleProps} className="text-muted-foreground cursor-grab active:cursor-grabbing shrink-0">
                                            <GripVertical className="w-3.5 h-3.5" />
                                          </div>
                                          <Checkbox checked={true} onCheckedChange={() => toggleCol(col.id)} id={`col-${col.id}`} />
                                          <label htmlFor={`col-${col.id}`} className="flex-1 text-sm cursor-pointer">{col.label}</label>
                                          <button
                                            type="button"
                                            title={isPinned ? "Unpin column" : "Pin column"}
                                            onClick={() => setFormFixedColumnIds((prev) => isPinned ? prev.filter((id) => id !== col.id) : [...prev, col.id])}
                                            className={`p-0.5 rounded hover:bg-muted transition-colors ${isPinned ? "text-primary" : "text-muted-foreground"}`}
                                          >
                                            <Pin className="w-3 h-3" />
                                          </button>
                                        </div>
                                      )}
                                    </Draggable>
                                  );
                                })}
                                {provided.placeholder}
                              </div>
                            )}
                          </Droppable>
                        </DragDropContext>
                        {filteredUnchecked.length > 0 && (
                          <div className="border-t border-border max-h-24 overflow-y-auto divide-y divide-border">
                            {filteredUnchecked.map((col) => (
                              <div key={col.id} className="flex items-center gap-2.5 px-3 py-2 opacity-50">
                                <div className="w-3.5 h-3.5 shrink-0" />
                                <Checkbox checked={false} onCheckedChange={() => toggleCol(col.id)} id={`col-${col.id}`} />
                                <label htmlFor={`col-${col.id}`} className="flex-1 text-sm cursor-pointer">{col.label}</label>
                              </div>
                            ))}
                          </div>
                        )}
                      </div>
                    );
                  })()}
                </TabsContent>

                {/* FILTERS TAB */}
                <TabsContent value="filters" className="mt-3 space-y-3">


                  <div className="space-y-2 max-h-64 overflow-y-auto">
                    {formFilters.filters.length === 0 && (
                      <p className="text-sm text-muted-foreground text-center py-4">No filters yet. Add one below.</p>
                    )}
                    {formFilters.filters.map((fi, idx) => {
                      const opts = getFieldOptions(fi.field);
                      return (
                        <div key={idx} className="border border-border rounded-lg p-3 space-y-2">
                          <div className="flex items-center gap-2">
                            {idx === 0 ? (
                              <span className="text-xs font-medium text-muted-foreground w-16 shrink-0">WHERE</span>
                            ) : (
                              <Select value={fi.operator || "and"} onValueChange={(v) => updateFilter(idx, { operator: v })}>
                                <SelectTrigger className="h-7 text-xs w-16 shrink-0"><SelectValue /></SelectTrigger>
                                <SelectContent>
                                  <SelectItem value="and">AND</SelectItem>
                                  <SelectItem value="or">OR</SelectItem>
                                  <SelectItem value="not">NOT</SelectItem>
                                </SelectContent>
                              </Select>
                            )}
                            <Select value={fi.field || "none"} onValueChange={(v) => updateFilter(idx, { field: v === "none" ? "" : v, values: [] })}>
                              <SelectTrigger className="h-7 text-xs flex-1"><SelectValue placeholder="Select field…" /></SelectTrigger>
                              <SelectContent>
                                <SelectItem value="none">Select field…</SelectItem>
                                {filterableFields.map((f) => <SelectItem key={f.id} value={f.id}>{f.label}</SelectItem>)}
                              </SelectContent>
                            </Select>
                            <button type="button" onClick={() => removeFilter(idx)} className="p-1 rounded hover:bg-muted text-muted-foreground hover:text-destructive">
                              <X className="w-3.5 h-3.5" />
                            </button>
                          </div>
                          {fi.field && (
                            <div className="pl-20 flex flex-wrap gap-1.5">
                              {opts.map((val) => (
                                <button
                                  key={val}
                                  type="button"
                                  onClick={() => toggleFilterValue(idx, val)}
                                  className={`px-2 py-0.5 rounded-full border text-xs transition-colors ${fi.values.includes(val) ? "bg-primary text-primary-foreground border-primary" : "border-border hover:bg-muted"}`}
                                >
                                  {val}
                                </button>
                              ))}
                              {opts.length === 0 && <span className="text-xs text-muted-foreground">No values found in data</span>}
                            </div>
                          )}
                        </div>
                      );
                    })}
                  </div>

                  <Button variant="outline" size="sm" onClick={addFilter} className="gap-1.5 text-xs w-full">
                    <Plus className="w-3.5 h-3.5" /> Add Filter
                  </Button>
                </TabsContent>

                {/* ROLES TAB */}
                <TabsContent value="roles" className="mt-3 space-y-3">
                  <p className="text-xs text-muted-foreground">Restrict this view to specific user roles. Leave empty to allow all roles.</p>
                  <div className="flex gap-2">
                    <Input
                      value={roleInput}
                      onChange={(e) => setRoleInput(e.target.value)}
                      onKeyDown={(e) => { if (e.key === "Enter") { e.preventDefault(); addRole(); } }}
                      placeholder="e.g. admin, manager…"
                      className="h-8 text-xs flex-1"
                    />
                    <Button type="button" variant="outline" size="sm" onClick={addRole} className="h-8 text-xs gap-1">
                      <Plus className="w-3.5 h-3.5" /> Add
                    </Button>
                  </div>
                  {formRoles.length === 0 ? (
                    <div className="flex items-center gap-2 text-xs text-muted-foreground border border-dashed border-border rounded-lg p-3">
                      <ShieldCheck className="w-4 h-4" /> Visible to all roles
                    </div>
                  ) : (
                    <div className="flex flex-wrap gap-2">
                      {formRoles.map((r) => (
                        <div key={r} className="flex items-center gap-1 bg-primary/10 text-primary text-xs px-2.5 py-1 rounded-full border border-primary/20">
                          <ShieldCheck className="w-3 h-3" />
                          {r}
                          <button type="button" onClick={() => removeRole(r)} className="ml-1 hover:text-destructive"><X className="w-3 h-3" /></button>
                        </div>
                      ))}
                    </div>
                  )}
                </TabsContent>
              </Tabs>

              <DialogFooter>
                <Button variant="outline" onClick={() => setMode("list")}>Back</Button>
                <Button onClick={handleSave} disabled={saving || !formName.trim()} className="gap-2">
                  {saving && <Loader2 className="w-4 h-4 animate-spin" />}
                  {mode === "new" ? "Create & Apply" : "Save"}
                </Button>
              </DialogFooter>
            </div>
          )}
        </DialogContent>
      </Dialog>
    </div>
  );
}

function tryParseJSON(str) {
  try { return JSON.parse(str); } catch { return null; }
}